#!/usr/bin/env python3
"""Generate the seeded-defect review cases from their answer keys.

    gen_seeded.py            # (re)write prompt.md, case.yaml, scaffold.sh, selftest.json
    gen_seeded.py --check    # exit 1 if any generated file is out of date (used by the tests)

Each ``evals/review/seeded-*/`` directory holds a hand-written ``fixture/``
(the design package, with 5-10 planted defects), ``key/answer_key.json`` (the
planted defects, acceptable extra findings and decoys, as regexes) and
``key/good_findings.json`` (a realistic complete review). Everything else is
derived here so the in-harness graders and ``seeded_score.py`` can never
disagree about what counts as finding a defect:

* one ``defect-<ID>`` regex grader per planted defect, matching a single flat
  finding object whose ``file`` matches the key's ``file`` regex and whose
  text matches ``locator`` and ``keywords`` (the same rule seeded_score.py
  applies);
* one ``decoy-<ID>`` not_contains grader per decoy (a finding *located* on a
  deliberately correct item), a precision proxy inside the harness score;
* path graders: the findings file was written with Write, no design file was
  edited, and (with-only indicator) a Forge reviewer agent was dispatched;
* ``selftest.json``: ``good`` (the good review), ``bad-missing-<ID>`` for every
  defect, ``bad-decoy-<ID>`` for every decoy, ``bad-no-findings`` and
  ``bad-edited-design``.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent.parent
REVIEW = EVALS / "review"
FINDINGS_FORMAT = (EVALS / "_tools" / "findings_format.md").read_text().strip()

TITLES = {
    "seeded-wearable": "PulseBand wrist sensor rev B",
    "seeded-enclosure": "SensorHub enclosure rev A",
    "seeded-power-board": "NodeLink RS-485 power board rev A",
}
SMOKE = {"seeded-wearable"}
MAX_TURNS = 40
TIMEOUT_S = 1800

PROMPT = """This repo holds the {title} design package, heading for its G2 (CDR) gate. Review it as an independent reviewer: find every defect that affects requirements, safety, fit, function, manufacturability or cost (not style), and give the numbers that show each one. Do not change any file other than the findings file.

{fmt}
"""

SCAFFOLD = """#!/usr/bin/env bash
# Seeds the run's workspace: Forge project template + this case's fixture/ (see ../../_lib/scaffold.sh).
CASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$CASE_DIR/../../_lib/scaffold.sh"
forge_eval_scaffold "$CASE_DIR" --template
"""


def q(s: str) -> str:
    """YAML single-quoted scalar."""
    return "'" + s.replace("'", "''") + "'"


def defect_pattern(e: dict) -> str:
    return (r'\{(?=[^{}]*"file"\s*:\s*"[^"]*(?:' + e["file"] + r')[^"]*")'
            r'(?=[^{}]*(?:' + e["locator"] + r'))(?=[^{}]*(?:' + e["keywords"] + r'))[^{}]*\}')


def decoy_pattern(e: dict) -> str:
    return (r'\{(?=[^{}]*"file"\s*:\s*"[^"]*(?:' + e["file"] + r')[^"]*")'
            r'(?=[^{}]*"location"\s*:\s*"[^"]*(?:' + e["locator"] + r')[^"]*")'
            r'(?=[^{}]*(?:' + e["keywords"] + r'))[^{}]*\}')


def _first_alt(rx: str) -> str:
    alt = rx.split("|")[0]
    alt = re.sub(r"\\b", "", alt)
    alt = alt.replace("\\.", ".").replace(" ?", " ").replace("\\", "")
    return alt


def case_yaml(slug: str, key: dict) -> str:
    rel = key["findings_path"]
    tgt = f"{{ source: file, path: {rel} }}"
    lines = [
        "# GENERATED by evals/_tools/gen_seeded.py from key/answer_key.json -- do not edit by hand.",
        'schema_version: "1.1"',
        f"name: {key['case']}",
        f"description: {q('Seeded-defect review: ' + str(len(key['defects'])) + ' planted defects, ' + str(len(key.get('decoys', []))) + ' decoys. Recall/precision computed by _tools/seeded_score.py.')}",
        f"tags: [review, seeded{', smoke' if slug in SMOKE else ''}]",
        "context:",
        "  scaffold_script: scaffold.sh",
        "graders:",
        "  - name: findings-written",
        "    type: regex",
        f"    target: {tgt}",
        "    pattern: " + q(r'"findings"\s*:\s*\[\s*\{'),
        "    weight: 1",
    ]
    for d in key["defects"]:
        lines += [
            f"  - name: defect-{d['id']}",
            "    type: regex",
            f"    target: {tgt}",
            "    flags: i",
            "    pattern: " + q(defect_pattern(d)),
            "    weight: 1",
        ]
    for d in key.get("decoys", []):
        lines += [
            f"  - name: decoy-{d['id']}",
            "    type: regex",
            f"    target: {tgt}",
            "    flags: i",
            "    match: not_contains",
            "    pattern: " + q(decoy_pattern(d)),
            "    weight: 0.5",
        ]
    lines += [
        "  - name: wrote-findings-with-write",
        "    type: tool_used",
        "    tool: Write",
        "    input_match: " + q(re.escape(rel)),
        "    weight: 0.5",
        "  - name: no-design-edits",
        "    type: tool_used",
        "    tool: Edit",
        "    input_match: " + q(r'"file_path":"[^"]*/(cad|ecad|params|requirements|analysis|docs|tests|evidence|firmware|reviews)/'),
        "    max: 0",
        "    min: 0",
        "    arm: both",
        "    weight: 1",
        "  - name: forge-reviewer-dispatched",
        "    type: tool_used",
        "    tool: Agent",
        "    input_match: " + q(r"forge:(verification-evaluator|red-team)"),
        "    arm: with-only",
    ]
    return "\n".join(lines) + "\n"


def prompt_md(slug: str) -> str:
    fm = [
        "---",
        f"max_turns: {MAX_TURNS}",
        f"timeout_seconds: {TIMEOUT_S}",
        "allowed_tools: [Read, Glob, Grep, Write, Agent, Skill, TodoWrite]",
        "---",
        "",
    ]
    return "\n".join(fm) + PROMPT.format(title=TITLES[slug], fmt=FINDINGS_FORMAT)


def selftest(key: dict, good: dict) -> dict:
    rel = key["findings_path"]
    reads = [{"tool": "Read", "input": {"file_path": f"/w/{p}"}} for p in
             ("requirements/requirements.md", "params/params.toml")]
    write = {"tool": "Write", "input": {"file_path": f"/w/{rel}", "content": "..."}}
    variants: dict = {
        "good": {"files": {rel: good}, "created": [rel], "tools": reads + [write],
                 "last_message": "Review done; findings in out/review/findings.json.", "expect": "all_pass"},
    }
    # which good finding carries which defect (by the scorer's own matching)
    sys.path.insert(0, str(EVALS / "_tools"))
    from seeded_score import _max_matching  # noqa: E402
    assign = _max_matching(good["findings"], key["defects"])
    for i, j in sorted(assign.items(), key=lambda t: t[1]):
        d = key["defects"][j]
        kept = [f for k, f in enumerate(good["findings"]) if k != i]
        variants[f"bad-missing-{d['id']}"] = {"base": "good", "files": {rel: {"schema": good["schema"], "findings": kept}},
                                             "expect": {f"defect-{d['id']}": False}}
    for d in key.get("decoys", []):
        fp = {"file": _first_alt(d["file"]), "location": _first_alt(d["locator"]), "category": "review",
              "severity": "major", "description": _first_alt(d["keywords"])}
        variants[f"bad-decoy-{d['id']}"] = {"base": "good",
                                           "files": {rel: {"schema": good["schema"], "findings": good["findings"] + [fp]}},
                                           "expect": {f"decoy-{d['id']}": False}}
    variants["bad-no-findings"] = {
        "base": "good", "files": {rel: None}, "created": [], "tools": reads,
        "expect": {"findings-written": False, "wrote-findings-with-write": False,
                   **{f"defect-{d['id']}": False for d in key["defects"]}},
        "why": "a missing file fails every file-target grader, including not_contains decoy graders",
    }
    variants["bad-no-findings"]["expect"].update({f"decoy-{d['id']}": False for d in key.get("decoys", [])})
    variants["bad-edited-design"] = {"base": "good",
                                     "tools": reads + [{"tool": "Edit", "input": {"file_path": "/w/params/params.toml", "old_string": "a", "new_string": "b"}}, write],
                                     "expect": {"no-design-edits": False}}
    variants["bad-no-reviewer-agent"] = {"base": "good", "expect": {"forge-reviewer-dispatched": False},
                                         "why": "good omits the Agent call on purpose; this indicator is with-only"}
    variants["good"]["tools"] = reads + [{"tool": "Agent", "input": {"subagent_type": "forge:verification-evaluator",
                                                                     "prompt": "review"}}, write]
    variants["bad-no-reviewer-agent"]["tools"] = reads + [write]
    return {"variants": variants}


def generate() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for d in sorted(REVIEW.glob("seeded-*")):
        key = json.loads((d / "key" / "answer_key.json").read_text())
        good = json.loads((d / "key" / "good_findings.json").read_text())
        out[d / "case.yaml"] = case_yaml(d.name, key)
        out[d / "prompt.md"] = prompt_md(d.name)
        out[d / "scaffold.sh"] = SCAFFOLD
        out[d / "selftest.json"] = json.dumps(selftest(key, good), indent=1) + "\n"
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args()
    stale = []
    for path, text in generate().items():
        if ns.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(path)
        else:
            path.write_text(text)
            if path.name == "scaffold.sh":
                path.chmod(0o755)
    if stale:
        print("stale generated files (run gen_seeded.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
